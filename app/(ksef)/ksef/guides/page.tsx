import type { Metadata } from 'next';
import Link from 'next/link';
import { ArticleShell } from '@/components/ksef/ArticleShell';
import { Icon } from '@/components/ksef/Icon';
import StructuredData from '@/components/StructuredData';
import { KSEF_NAME, ksefUrl } from '@/data/ksef/config';
import { GUIDES, guideFigures } from '@/data/ksef/guides';
import { KSEF_OG } from '@/data/ksef/screenshots';

const title = 'Poradniki KSeF: odbieranie faktur, logowanie, ZAW-FA, certyfikat i terminy';
const description =
  'Praktyczne poradniki o KSeF oparte na materiałach Ministerstwa Finansów: jak odbierać i pobierać faktury, jak się zalogować, ZAW-FA, certyfikat KSeF, korekty, JPK i terminy na 2027 rok.';

export const metadata: Metadata = {
  title: { absolute: title },
  description,
  alternates: { canonical: ksefUrl('/guides') },
  openGraph: {
    title,
    description,
    url: ksefUrl('/guides'),
    siteName: KSEF_NAME,
    locale: 'pl_PL',
    type: 'website',
    images: [{ url: KSEF_OG.png, width: KSEF_OG.width, height: KSEF_OG.height, alt: KSEF_OG.alt }],
  },
};

const formatDate = (iso: string) =>
  new Date(iso).toLocaleDateString('pl-PL', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });

// The guide's first diagram scaled to 640x360 (generated by scripts/ksef-figures/render.mjs).
function GuideThumb({ name, eager }: { name?: string; eager: boolean }) {
  if (!name) return null;
  return (
    <picture className="fk-guide-thumb">
      <img src={`/ksef/figures/${name}-t.webp`} width={640} height={360} alt="" loading={eager ? 'eager' : 'lazy'} decoding="async" />
    </picture>
  );
}

export default function KsefGuides() {
  return (
    <>
      <StructuredData
        data={[
          {
            '@context': 'https://schema.org',
            '@type': 'CollectionPage',
            name: title,
            description,
            url: ksefUrl('/guides'),
            inLanguage: 'pl-PL',
            mainEntity: {
              '@type': 'ItemList',
              itemListElement: GUIDES.map((g, i) => ({ '@type': 'ListItem', position: i + 1, url: ksefUrl(`/${g.slug}`), name: g.title })),
            },
          },
          {
            '@context': 'https://schema.org',
            '@type': 'BreadcrumbList',
            itemListElement: [
              { '@type': 'ListItem', position: 1, name: KSEF_NAME, item: ksefUrl() },
              { '@type': 'ListItem', position: 2, name: 'Poradniki', item: ksefUrl('/guides') },
            ],
          },
        ]}
      />
      <ArticleShell
        crumbs={[{ label: KSEF_NAME, href: '/' }, { label: 'Poradniki' }]}
        label="Poradniki"
        title="KSeF w praktyce"
        lede="Krótkie odpowiedzi i pełne wyjaśnienia najczęstszych pytań o Krajowy System e-Faktur. Każdy poradnik podaje stan prawny, datę aktualizacji i oficjalne źródła Ministerstwa Finansów."
      >
        <ul className="fk-guide-cards">
          {GUIDES.map((g, i) => (
            <li key={g.slug} data-reveal>
              <Link href={`/${g.slug}`}>
                <GuideThumb name={guideFigures(g)[0]} eager={i < 2} />
                <span className="fk-mono">Aktualizacja {formatDate(g.updated)}</span>
                <h2>{g.title}</h2>
                <p>{g.summary[0]}</p>
                <ul>
                  {g.sections.slice(0, 3).map((s) => <li key={s.id}>{s.h2}</li>)}
                </ul>
                <span className="fk-guide-more">Czytaj poradnik <Icon name="chevron" size={16} /></span>
              </Link>
            </li>
          ))}
        </ul>
        <p className="fk-disclaimer">
          Poradniki mają charakter informacyjny i nie są poradą podatkową. Szukasz aplikacji do odbierania faktur z KSeF?{' '}
          <Link href="/">Zobacz Faktury KSeF</Link>.
        </p>
      </ArticleShell>
    </>
  );
}
