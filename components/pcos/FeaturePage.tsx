import Image from 'next/image';
import Link from 'next/link';
import type { ReactNode } from 'react';
import { PcosShellBare } from '@/components/PcosLegal';
import { FEATURES, PCOS_BASE, PCOS_FEATURES_UPDATED, SAMPLE_NOTE, type Feature, type Section, type Shot } from '@/data/pcos/features';
import { pcosStyles } from '@/app/[locale]/pcos/pcos-styles';
import CycleBars from './CycleBars';
import Reveal from './Reveal';
import ScoreCard, { type ScoreData } from './ScoreCard';
import { SCORE_EXAMPLES, SCORE_RULES, GRADE_SCALE } from '@/data/pcos/scores';

const webp = (f: string) => f.replace(/\.png$/, '.webp');

/** Phone frame around a real app screenshot. */
export function Phone({ shot, priority, float }: { shot: Shot; priority?: boolean; float?: boolean }) {
  return (
    <div className={`pcx-phone${float ? ' pcx-float' : ''}`}>
      <Image src={`/pcos/${webp(shot.file)}`} alt={shot.alt} width={720} height={1564} priority={priority} sizes="(max-width: 860px) 70vw, 300px" />
    </div>
  );
}

/** One phone that crossfades between up to three screenshots. */
export function PhoneStack({ shots, priority }: { shots: Shot[]; priority?: boolean }) {
  if (shots.length === 1) return <Phone shot={shots[0]} priority={priority} float />;
  return (
    <div className={`pcx-phone pcx-float pcx-stack n${shots.length}`}>
      {shots.map((s, i) => (
        <Image key={s.file} src={`/pcos/${webp(s.file)}`} alt={s.alt} width={720} height={1564} priority={priority && i === 0} sizes="(max-width: 860px) 70vw, 300px" />
      ))}
    </div>
  );
}

function SectionBlock({ s }: { s: Section; f?: Feature }) {
  const text: ReactNode = (
    <div>
      <h2 className="pcx-h2">{s.h2}</h2>
      {s.paras.map((p) => (
        <p key={p.slice(0, 40)} className="pcx-p">{p}</p>
      ))}
      {s.demo === 'cycles' && <CycleBars lengths={[31, 29, 38, 33, 41, 30]} />}
      {s.timeline && (
        <Reveal>
          <div className="pcx-track" style={{ ['--n' as string]: s.timeline.length }}>
            <div className="pcx-track-line"><i /></div>
            {s.timeline.map((t, i) => (
              <div key={t.label} className="pcx-node" style={{ animationDelay: `${0.25 + i * 0.28}s` }}>
                <b>{t.label}</b>
                <span>{t.sub}</span>
              </div>
            ))}
          </div>
        </Reveal>
      )}
      {s.demo === 'rules' && (
        <>
          <div className="pcx-rules">
            {SCORE_RULES.map(([rule, pts]) => (
              <div key={rule} className="pcx-rules-row">
                <span>{rule}</span>
                <span className={`pcx-pts ${pts.startsWith('+') ? 'up' : 'down'}`}>{pts}</span>
              </div>
            ))}
          </div>
          <div className="pcx-scale" aria-label="Grade scale">
            {GRADE_SCALE.map(([g, range, color], i) => (
              <div key={g} style={{ background: color, animationDelay: `${i * 0.12}s` }}>
                <b>{g}</b>
                {range}
              </div>
            ))}
          </div>
        </>
      )}
      {s.demo === 'pdf' && (
        <figure style={{ margin: '12px 0 0', maxWidth: 520 }}>
          <div style={{ border: '1px solid var(--line)', borderRadius: 14, overflow: 'hidden', background: '#fff', boxShadow: '0 18px 40px -20px rgba(46,42,69,.3)' }}>
            <Image src="/pcos/report-pdf-preview.webp" alt="The doctor report PDF generated by the app from sample entries: summary, worth discussing, questions, cycle lengths, bleeding, pain and symptoms" width={794} height={1500} sizes="(max-width: 860px) 90vw, 520px" style={{ width: '100%', height: 'auto', display: 'block' }} />
          </div>
          <figcaption className="pcx-cap" style={{ textAlign: 'left' }}>
            First page of the report, built from sample entries. <a href="/pcos/sample-doctor-report.pdf" style={{ color: 'var(--peach-strong)', fontWeight: 700 }}>Open the full sample PDF</a>
          </figcaption>
        </figure>
      )}
      {s.demo === 'score' && (
        <div style={{ display: 'flex', gap: 18, flexWrap: 'wrap', marginTop: 8 }}>
          {SCORE_EXAMPLES.map((x: ScoreData) => (
            <ScoreCard key={x.name} s={x} />
          ))}
        </div>
      )}
    </div>
  );
  if (!s.shots?.length) return <Reveal>{text}</Reveal>;
  const shots = (
    <div>
      <div className="pcx-duo">
        {s.shots.map((sh) => (
          <Phone key={sh.file} shot={sh} />
        ))}
      </div>
      {s.caption && <p className="pcx-cap">{s.caption}</p>}
    </div>
  );
  return (
    <Reveal>
      <div className={`pcx-split${s.flip ? ' flip' : ''}`} style={s.shots.length > 1 ? { gridTemplateColumns: s.flip ? '540px 1fr' : '1fr 540px' } : undefined}>
        {text}
        {shots}
      </div>
    </Reveal>
  );
}

export default function FeaturePage({ f }: { f: Feature }) {
  const url = `${PCOS_BASE}/${f.slug}`;
  const related = f.related.map((slug) => FEATURES.find((x) => x.slug === slug)).filter(Boolean) as Feature[];
  const ld = [
    {
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: f.faq.map((x) => ({ '@type': 'Question', name: x.q, acceptedAnswer: { '@type': 'Answer', text: x.a } })),
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'PCOS & Endo Tracker', item: PCOS_BASE },
        { '@type': 'ListItem', position: 2, name: f.name, item: url },
      ],
    },
  ];
  return (
    <PcosShellBare>
      <style>{pcosStyles}</style>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(ld) }} />

      <section className="pcx-hero">
        <div className="pcx-hero-inner">
          <div>
            <div className="pcx-crumbs"><Link href="/pcos">PCOS &amp; Endo Tracker</Link> / {f.name}</div>
            <h1 className="pcx-h1">{f.h1[0]}<em>{f.h1[1]}</em></h1>
            <p className="pcx-lede">{f.lede}</p>
            <div className="pcx-tags">
              <span className={`pcx-tag ${f.tier === 'Free' ? 'free' : f.tier === 'Premium' ? 'premium' : ''}`}>{f.tier}</span>
              {f.tags.map((t) => (
                <span key={t} className="pcx-tag">{t}</span>
              ))}
            </div>
          </div>
          <PhoneStack shots={f.hero} priority />
        </div>
      </section>

      {f.sections.map((s, i) => (
        <section key={s.h2} className={`pcx-sec${i % 2 ? ' alt' : ''}`}>
          <div className="pcx-sec-inner">
            <SectionBlock s={s} f={f} />
          </div>
        </section>
      ))}

      {f.steps && (
        <section className="pcx-sec">
          <div className="pcx-sec-inner">
            <Reveal>
              <h2 className="pcx-h2">{f.stepsH2}</h2>
              <ol className="pcx-steps">
                {f.steps.map((s) => (
                  <li key={s.title}><strong>{s.title}.</strong> {s.body}</li>
                ))}
              </ol>
            </Reveal>
          </div>
        </section>
      )}

      <section className={`pcx-sec${f.steps ? ' alt' : ''}`}>
        <div className="pcx-sec-inner">
          <Reveal>
            {f.facts && (
              <>
                <h2 className="pcx-h2">{f.factsH2 ?? 'Details'}</h2>
                <div className="pcx-facts">
                  {f.facts.map((x) => (
                    <div key={x.t} className="pcx-fact"><h3>{x.t}</h3><p>{x.d}</p></div>
                  ))}
                </div>
              </>
            )}
            <div className="pcx-not"><strong>{f.not.t}</strong><p>{f.not.p}</p></div>
          </Reveal>
        </div>
      </section>

      <section className={`pcx-sec${f.steps ? '' : ' alt'}`}>
        <div className="pcx-sec-inner pcx-faq">
          <Reveal>
            <h2 className="pcx-h2">Questions</h2>
            {f.faq.map((x) => (
              <details key={x.q}><summary>{x.q}</summary><p>{x.a}</p></details>
            ))}
            <p className="pcx-sample">{SAMPLE_NOTE} Not a medical device. Updated {new Date(PCOS_FEATURES_UPDATED).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}.</p>
          </Reveal>
        </div>
      </section>

      <section className="pcx-sec">
        <div className="pcx-sec-inner">
          <Reveal>
            <h2 className="pcx-h2">Related</h2>
            <div className="pcx-more">
              {related.map((r) => (
                <Link key={r.slug} href={`/pcos/${r.slug}`}><strong>{r.name}</strong><span>{r.short}</span></Link>
              ))}
              <Link href="/pcos"><strong>All features</strong><span>Back to the app overview, with every feature and what is free.</span></Link>
            </div>
          </Reveal>
        </div>
      </section>
    </PcosShellBare>
  );
}
